import { buzz, useFeedbackOn } from '../../lib/feedback';

/**
 * Тактильный отклик на нажатие: кладётся последним ребёнком в кнопку.
 *
 * Android — Vibration API. На iPhone её нет (Safari не реализует), но у
 * системного переключателя `<input type="checkbox" switch>` есть родной
 * тактильный щелчок (Safari 18+). Программный `label.click()` Apple закрыла в
 * iOS 26.5, поэтому палец должен попасть по самому `<label>`: прозрачный
 * label лежит поверх кнопки и пересылает настоящий тап в спрятанный
 * переключатель. Клик по label всплывает в кнопку как обычно, а клик
 * переключателя дальше не идёт — обработчик кнопки срабатывает один раз.
 *
 * Размер — не меньше 44×44, как невидимая зона HIT_SLOP_44. Сам `::after`
 * этой зоны лежит поверх label и перехватил бы тап на всей площади, поэтому
 * index.css у кнопки с label гасит ему pointer-events и заодно ставит ей
 * `relative` (правило в @layer base — `absolute` из утилит его бьёт).
 * Приём — как у ios-haptics 3.3 (MIT); на устройстве не проверено.
 *
 * Где стоит (PROTOCOL §6.4): там, где тап меняет состояние, — переключатель,
 * отметка, сегмент, чип, оценка, шаг «−/+», «Скопировать». Обычные кнопки и
 * переходы молчат. Выключатель «Отклик на касания» убирает накладку целиком.
 *
 * `off` — тап сейчас ничего не меняет (выбранный сегмент): накладка остаётся в
 * документе, но пропускает касание сквозь себя. Убирать её нельзя: переключатель
 * щёлкает уже ПОСЛЕ обработчика кнопки, и к этому моменту он должен стоять в
 * документе — сегмент, выбранный этим самым тапом, иначе промолчал бы.
 *
 * `fit` — накладка ровно по кнопке, без выступа до 44: для мелкой кнопки без
 * HIT_SLOP_44 впритык к другой цели (чип реакции под пузырём сообщения), где
 * выступ забрал бы чужие тапы.
 *
 * Вибрация — в клике самого переключателя, а не label: label пересылает клик
 * туда своим действием по умолчанию, и обработчик, отменивший клик
 * (preventDefault — TaskCheck после удержания), гасит разом и щелчок iPhone,
 * и вибрацию Android.
 */
export function Haptic({ off = false, fit = false }: { off?: boolean; fit?: boolean }) {
  if (!useFeedbackOn()) return null;
  return (
    <label
      aria-hidden="true"
      data-haptic={off ? 'off' : ''}
      className={`absolute touch-manipulation ${
        fit ? 'inset-0' : 'top-1/2 left-1/2 h-[max(100%,44px)] w-[max(100%,44px)] -translate-x-1/2 -translate-y-1/2'
      } ${off ? 'pointer-events-none' : ''}`}
    >
      <input
        type="checkbox"
        tabIndex={-1}
        // `switch` нет в типах React — атрибут передаётся строкой через spread.
        {...{ switch: '' }}
        onClick={(e) => {
          e.stopPropagation();
          buzz();
        }}
        className="invisible absolute size-px"
      />
    </label>
  );
}
