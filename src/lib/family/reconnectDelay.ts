// Пауза перед следующей попыткой подключиться к семейному чату.
//
// Пауза была постоянной — три секунды. Пока разрыв временный (сеть моргнула),
// так и правильно. Но разрыв, который сам не проходит — приложение открыто со
// снятого с эксплуатации адреса, отозван ключ, лежит сервер, — превращал
// каждое устройство в 1200 попыток в час, а в каждой попытке три запроса к
// воркеру: задача, тикет, сам сокет.
//
// Так и вышло 7–8 сентября 2026: пара забытых открытыми окон выдавала около
// восьми тысяч запросов в час круглосуточно, за сутки выбрала дневной лимит
// бесплатного плана Cloudflare (100 000 запросов), и сервер начал отвечать 429
// вообще всем — обмен встал у всей семьи, включая исправные устройства.
//
// Удвоение с потолком в минуту делает такой же суточный отказ примерно в
// двадцать раз дешевле. На человеке это не сказывается: возврат в приложение
// подключает сразу, не дожидаясь таймера (см. FamilyRunner — visibilitychange,
// focus, online).
export const RECONNECT_BASE_MS = 3000;
export const RECONNECT_MAX_MS = 60_000;

/** Пауза перед попыткой номер attempt (0 — первая после разрыва).
 *
 *  Разброс до четверти паузы обязателен: устройства теряют связь
 *  одновременно (упал сервер) и без разброса вернулись бы тоже
 *  одновременно — тем самым залпом, от которого сервер и лёг. */
export function reconnectDelay(attempt: number, jitter: number = Math.random()): number {
  const step = Math.min(RECONNECT_BASE_MS * 2 ** Math.max(0, attempt), RECONNECT_MAX_MS);
  return Math.round(step * (1 + 0.25 * jitter));
}
