// Адрес сервера — единственная точка на всё приложение.
//
// Раньше он был вписан строкой в пяти файлах сразу, и это оказалось дорого.
// Клиент, запущенный на машине разработчика (дев-сервер, браузерные тесты),
// ходил ровно туда же, куда боевое приложение, — в живой сервер семьи. А так
// как localhost нет и не может быть в списке разрешённых адресов сервера,
// каждая такая вкладка получала отказ, считала это обрывом связи и ломилась
// заново каждые три секунды. Круглосуточно, пока окно открыто.
//
// Именно так 5-8 сентября 2026 был выбран дневной лимит бесплатного плана
// Cloudflare (100 000 запросов и столько же записей в Durable Object), и
// сервер начал отвечать 429 ВСЕМ — обмен встал у всей семьи, а причина сидела
// на рабочем столе разработчика.
//
// Теперь адрес берётся из окружения. Боевая сборка (vite build) переменной не
// видит и получает адрес по умолчанию — тот же, что был. Дев-сервер читает
// .env.development, где стоит локальный адрес: попасть с машины разработчика
// в боевой сервер стало нельзя случайно, только осознанной правкой.
export const WORKER_URL: string =
  import.meta.env.VITE_WORKER_URL ?? 'https://life-hub-push.xabos161rus.workers.dev';

/** Тот же адрес для сокета: https → wss, http → ws. */
export const WORKER_WS_URL: string = WORKER_URL.replace(/^http/, 'ws');
