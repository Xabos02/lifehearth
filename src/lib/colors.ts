/** Тёмный глиф поверх заливок пользовательским цветом — то же значение, что
 *  --app-on-light (oklch(0.18 0.015 285)) в index.css. */
export const ON_COLOR_DARK = '#111118';

function luminance(h: string): number {
  const [r, g, b] = [0, 2, 4].map((i) => {
    const c = parseInt(h.slice(i, i + 2), 16) / 255;
    return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
  });
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

/** Нужен ли поверх этого цвета тёмный глиф, а не белый: какой из двух
 *  контрастнее по WCAG. Прежний порог яркости (186) оставлял белый на 23
 *  цветах палитры из 27 — 1.74–4.47 при норме 4.5 (канва design/contrast). */
export function isLightColor(hex: string): boolean {
  let h = hex.replace('#', '');
  // Цвет участника с сервера бывает и коротким (#fff): без разворота белый
  // участник получал белый инициал.
  if (h.length === 3) h = [...h].map((c) => c + c).join('');
  if (h.length < 6) return false;
  const l = luminance(h);
  return (l + 0.05) / (luminance(ON_COLOR_DARK.slice(1)) + 0.05) > 1.05 / (l + 0.05);
}
