import { t } from './i18n';

/** Длительность в минутах — человеческим текстом.
 *
 *  Жила двумя одинаковыми копиями — в статистике и в редакторе задачи. Третьим
 *  местом стал раздел «Обучение» (сколько занимался), поэтому переехала сюда.
 *  Пробелы внутри строк неразрывные: число не должно отрываться от единицы. */

/** «45 мин», «1 ч», «1 ч 30 мин». */
export function formatDuration(min: number): string {
  const h = Math.floor(min / 60);
  const m = min % 60;
  if (h === 0) return t('{m}\u00A0мин', { m });
  return m === 0 ? t('{h}\u00A0ч', { h }) : t('{h}\u00A0ч {m}\u00A0мин', { h, m });
}

/** Компактная подпись столбца графика: «45 мин», «2ч», «1.5ч». Пустая строка
 *  для нуля: подписывать нулевые столбики нечем, они и так пустые. */
export function compactDuration(min: number): string {
  if (min === 0) return '';
  if (min < 60) return t('{m}\u00A0мин', { m: min });
  const h = min / 60;
  return t('{h}ч', { h: Number.isInteger(h) ? h : h.toFixed(1) });
}
