// нового» внутри приложения и push-уведомление, которое рассылает воркер
// (scripts/notify-update.mjs). Раньше текст пуша набирался руками при вызове
// эндпоинта, и он мог разойтись с тем, что на самом деле поменялось.
//
// Список в коде, а не в JSON рядом со сборкой: JSON пришлось бы дозагружать
// запросом, а обновление человек чаще всего открывает сразу после перезапуска,
// когда сети может не быть вовсе.

export interface Release {
  /** Версия. Растёт по порядку; сравнивать только через compareVersions. */
  version: string;
  /** Дата выпуска, 'YYYY-MM-DD'. */
  date: string;
  /** Пункты — человеческим языком, не сообщениями коммитов. Каждый должен
   *  отвечать на вопрос «что мне теперь доступно», а не «что вы починили». */
  items: string[];
}

