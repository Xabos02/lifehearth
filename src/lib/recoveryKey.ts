// Ключ восстановления как ВЕЩЬ, которую человек хранит.
//
// Технически это тот же пакет доступа (crypto.ts, v:1): id аккаунта, токен и
// ключ шифрования в одной строке base64. Но человеку достаётся не «строка
// base64», а файл, который через полгода надо узнать в списке загрузок и
// понять, что с ним делать. Поэтому здесь три вещи: как файл называется, что
// написано внутри и как достать код обратно из того, что человек вставил.
//
// Откуда это взялось. Файл назывался life-hub-sync-key.txt — по имени, которое
// приложение носило до переименования, — и содержал 224 символа без единого
// слова. Владелец нашёл свой ключ в «Загрузках» случайно, по дате изменения,
// и не был уверен, что это он, пока не вставил.

import { t } from './i18n';

/** Имя файла: имя приложения, назначение по-русски и дата — чтобы файл можно
 *  было узнать в списке загрузок через полгода. */
export function recoveryKeyFilename(now = new Date()): string {
  const d = `${now.getFullYear()}-${String(now.getMonth() + 1).padStart(2, '0')}-${String(now.getDate()).padStart(2, '0')}`;
  return `lifehearth-klyuch-vosstanovleniya-${d}.txt`;
}

/** Содержимое файла: сначала объяснение человеку, потом сам код.
 *
 *  Порядок именно такой. Файл открывают в двух случаях: чтобы вспомнить, что
 *  это, и чтобы скопировать код. Первое важнее: код без объяснения выглядит
 *  как мусор, который удаляют при уборке. */
export function recoveryKeyFileText(code: string, now = new Date()): string {
  return [
    t('Ключ восстановления LifeHearth'),
    '',
    t('Этим кодом возвращают все записи, если телефон потерян или заменён.'),
    t('Второй копии ключа нет ни у кого, включая разработчика: потеряете — восстановить будет нечем.'),
    '',
    t('Куда вставлять: приложение → Настройки → Синхронизация → «У меня уже есть данные».'),
    t('Можно вставить весь этот файл целиком — приложение само найдёт код.'),
    '',
    t('Сохранён: {date}', { date: now.toLocaleDateString('ru-RU') }),
    '',
    code,
    '',
  ].join('\n');
}

/** Достать код из того, что человек вставил: голый код, файл целиком, файл с
 *  переносами от почтового клиента.
 *
 *  Человек вставляет не то, что мы задумали, а то, что у него в руках. Раньше
 *  поле принимало ровно голый код: вставленный файл целиком не подходил, и
 *  ошибка была одна на все случаи — «проверьте код». */
export function extractRecoveryCode(input: string): string {
  const direct = input.trim();
  if (looksLikeCode(direct)) return direct;
  // Строки файла: код — самая длинная строка, похожая на код.
  const best = direct
    .split(/\s+/)
    .filter(looksLikeCode)
    .sort((a, b) => b.length - a.length)[0];
  return best ?? direct;
}

/** base64url достаточной длины: пакет доступа — больше двухсот символов, а
 *  любое русское слово из шапки файла отсеивается первым же условием. */
function looksLikeCode(s: string): boolean {
  return s.length >= 40 && /^[A-Za-z0-9_-]+$/.test(s);
}

/** Показать код группами по 8 — чтобы глазами сверить сохранённое с тем, что
 *  на экране, и чтобы место обрыва было видно. */
export function groupCode(code: string, size = 8): string {
  return code.replace(new RegExp(`(.{${size}})`, 'g'), '$1 ').trim();
}
