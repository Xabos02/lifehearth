// Что сервер согласен хранить из текста напоминания.
//
// Текст хранится до срока, потому что приложение в это время закрыто. С
// 1.37.0 клиент шлёт его только шифротекстом (src/lib/reminderSeal.ts) —
// 'e2e1:…', расшифровывает телефон. Открытый текст сервер больше не хранит
// вовсе, кто бы его ни прислал: телефон, ещё не обновившийся до 1.37.0,
// получит нейтральное «Напоминание» — это цена, названная владельцу, за то,
// чтобы названия задач здесь не лежали (решение 24.09: «всё защищено»).
export const SEALED_PREFIX = 'e2e1:';

export function storableReminderText(title, body) {
  if (typeof body === 'string' && body.startsWith(SEALED_PREFIX)) return { title: '', body };
  return { title: '', body: '' };
}

// Записи, поставленные до правки, лежат открытым текстом до срока — иногда
// неделями. Крон раз в минуту стирает их текст (срабатывают нейтрально).
export const SCRUB_PLAIN_REMINDERS_SQL =
  "UPDATE reminders SET title = '', body = '' WHERE (title != '' OR body != '') AND body NOT LIKE 'e2e1:%'";
