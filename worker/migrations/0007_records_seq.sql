-- Курсор приёма — порядковый номер прихода на сервер, а не время правки.
--
-- Дефект, который это закрывает. Устройство просило «всё, что новее последней
-- полученной записи», а «новее» считалось по updated_at — метке, которую
-- ставит устройство-автор по СВОИМ часам в момент правки, а не сервер в момент
-- получения. Стоило записи прийти на сервер позже, чем другая, более свежая
-- по метке (телефон создал задачу без сети и отправил через час; часы двух
-- устройств разошлись на секунды), — и для всех, кто уже успел получить ту
-- свежую, эта запись становилась невидимой навсегда: сервер честно отвечал
-- «новее ничего нет». На сервере цела, на одном устройстве есть, на другом
-- нет, и причина ниоткуда не видна. Именно так задачи, заведённые ночью на
-- телефоне, не доезжали до мака.
--
-- seq растёт при КАЖДОЙ записи (вставке и обновлении) в пределах аккаунта и
-- никак не зависит от часов устройств. device_id — кто прислал: своё же
-- устройство эти записи не перечитывает, они у него и так есть.
--
-- Применять: wrangler d1 migrations apply life-hub-sync --remote — либо не
-- применять вовсе: воркер заводит эти колонки сам при первом обращении
-- (ensureRecordsSchema в src/index.js) и отмечает миграцию в d1_migrations.
-- Так сделано потому, что воркер деплоится из CI при push в main, меняющем
-- worker/**, а порядок «сначала миграция, потом деплой» ничем не гарантирован.
-- rowid хранит порядок первой вставки — лучшее приближение для уже лежащих
-- записей. Клиенты после обновления начинают с нуля и перечитывают историю
-- один раз (запись применяется, только если свежее локальной).
ALTER TABLE records ADD COLUMN seq INTEGER NOT NULL DEFAULT 0;
ALTER TABLE records ADD COLUMN device_id TEXT;
UPDATE records SET seq = rowid;
CREATE INDEX IF NOT EXISTS idx_records_seq ON records (account_id, seq);
