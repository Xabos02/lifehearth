import { defineConfig, devices } from '@playwright/test';

// Браузерные тесты. Отдельно от vitest намеренно: vitest проверяет чистые
// функции и работает за секунды, а сюда попадает то, что видно только в
// настоящем движке — вёрстка, жесты, IndexedDB, service worker.
//
// Чем это может упасть на чужой машине: браузер здесь предустановлен
// (PLAYWRIGHT_BROWSERS_PATH=/opt/pw-browsers), а на новой понадобится
// `npx playwright install chromium`.
// Порт можно переопределить: E2E_PORT=5299 npx playwright test.
//
// Без этого два прогона на одной машине (например, из двух рабочих копий)
// дерутся за 5199, и хуже того — reuseExistingServer молча переиспользует
// ЧУЖОЙ dev-сервер. Тесты тогда проверяют не тот код, который правишь:
// правка не влияет на результат, а мутационная проверка показывает зелёное
// там, где всё сломано.
const PORT = Number(process.env.E2E_PORT ?? 5199);

export default defineConfig({
  testDir: './e2e',
  // Дев-сервер отдаёт приложение по '/', а боевая сборка — по '/life-hub/'
  // (vite.config.ts: base зависит от command). Обратиться сюда по боевому пути
  // — значит попасть на несуществующий маршрут: оболочка отрисуется, а
  // содержимое экрана нет. Так и вышло при первом прогоне, и тесты этого не
  // заметили, потому что проверяли «#root не пуст».
  use: {
    baseURL: `http://127.0.0.1:${PORT}/`,
    // Размер iPhone 14 Pro: приложение мобильное, и почти все дефекты вёрстки,
    // которые ловились раньше, проявлялись именно на узком экране.
    ...devices['iPhone 14 Pro'],
    // Профиль устройства тянет за собой WebKit, а установлен здесь Chromium.
    // Нам нужна геометрия узкого экрана и тач, а не именно движок Safari.
    browserName: 'chromium',
    trace: 'retain-on-failure',
  },
  // Один браузер: гоняем не совместимость, а собственные регрессии.
  projects: [{ name: 'mobile-chromium' }],
  webServer: {
    command: `npm run dev -- --port ${PORT} --strictPort --host 127.0.0.1`,
    url: `http://127.0.0.1:${PORT}/`,
    reuseExistingServer: !process.env.CI,
    timeout: 60_000,
  },
  // Тесты пишут в одну и ту же IndexedDB через отдельные контексты, но
  // параллельные вкладки на слабой машине дают ложные таймауты.
  workers: process.env.CI ? 1 : 2,
  // Одна повторная попытка — и это не попытка спрятать поломку.
  //
  // 10.09.2026 за один день трижды случилось одно и то же: в общем прогоне
  // краснели тесты, которые поодиночке зелёные (ai, contrast, восстановление
  // на новом телефоне, вложение подпроекта). Причина не в проверках, а в
  // соседстве: два воркера, дев-сервер и браузеры на одной машине дают
  // таймауты там, где приложение исправно.
  //
  // Цена такого шума высокая: перестаёшь верить красному. С одной повторной
  // попыткой настоящая поломка падает дважды и остаётся красной, а шум
  // помечается как flaky — то есть виден отдельной строкой, а не смешивается
  // с реальными отказами. Разбор самой причины — отдельная работа (задача 19
  // в TASKS.md), retry её не отменяет.
  retries: 1,
  reporter: process.env.CI ? 'line' : 'list',
  expect: { timeout: 7000 },
});
